#!/bin/bash
. ./get_environment_type.sh

get_environment_type $2

./create_inventory.sh

. ./get_env.sh
. ./ansible_vars.sh

DOMAIN=$(get_env "$BASH_SOURCE" "DOMAIN")

API_SERVICE_SUBDOMAIN=$(get_env "$BASH_SOURCE" "API_SERVICE_SUBDOMAIN")

SERVICE_NAME=$(get_env "$BASH_SOURCE" "MCP_SERVICE_NAME")
SERVICE_SUBDOMAIN=$(get_env "$BASH_SOURCE" "MCP_SERVICE_SUBDOMAIN")

if [ -z "$SERVICE_NAME" ]; then
    SERVICE_NAME=mcp
fi

if [ -z "$SERVICE_SUBDOMAIN" ]; then
    SERVICE_SUBDOMAIN=mcp
fi

PORTAINER_USERNAME=$(get_env "$BASH_SOURCE" "PORTAINER_USERNAME")
PORTAINER_PASSWORD=$(get_env "$BASH_SOURCE" "PORTAINER_PASSWORD")
PORTAINER_SERVICE_SUBDOMAIN=$(get_env "$BASH_SOURCE" "PORTAINER_SERVICE_SUBDOMAIN")

RBAC_JWT_SECRET=$(get_env "$BASH_SOURCE" "RBAC_JWT_SECRET")

REDIS_PASSWORD=$(get_env "$BASH_SOURCE" "REDIS_PASSWORD")
REDIS_PORT=$(get_env "$BASH_SOURCE" "REDIS_PORT")

MCP_SERVICE_ALLOW_RBAC_SECRET_FALLBACK=$(get_env "$BASH_SOURCE" "MCP_SERVICE_ALLOW_RBAC_SECRET_FALLBACK")
MCP_SERVICE_ALLOWED_ORIGINS=$(get_env "$BASH_SOURCE" "MCP_SERVICE_ALLOWED_ORIGINS")
MCP_SERVICE_INTERNAL_TOKEN_EXCHANGE_SECRET=$(get_env "$BASH_SOURCE" "MCP_SERVICE_INTERNAL_TOKEN_EXCHANGE_SECRET")
MCP_SERVICE_OAUTH_JWT_SECRET=$(get_env "$BASH_SOURCE" "MCP_SERVICE_OAUTH_JWT_SECRET")
MCP_SERVICE_OAUTH_AUTH_CODE_TTL_SECONDS=$(get_env "$BASH_SOURCE" "MCP_SERVICE_OAUTH_AUTH_CODE_TTL_SECONDS")
MCP_SERVICE_OAUTH_ACCESS_TOKEN_TTL_SECONDS=$(get_env "$BASH_SOURCE" "MCP_SERVICE_OAUTH_ACCESS_TOKEN_TTL_SECONDS")
MCP_SERVICE_OAUTH_REFRESH_TOKEN_TTL_SECONDS=$(get_env "$BASH_SOURCE" "MCP_SERVICE_OAUTH_REFRESH_TOKEN_TTL_SECONDS")
MCP_SERVICE_OAUTH_CLIENT_TTL_SECONDS=$(get_env "$BASH_SOURCE" "MCP_SERVICE_OAUTH_CLIENT_TTL_SECONDS")
MCP_SERVICE_HTTP_MAX_BODY_BYTES=$(get_env "$BASH_SOURCE" "MCP_SERVICE_HTTP_MAX_BODY_BYTES")
MCP_SERVICE_HTTP_SESSION_IDLE_TTL_SECONDS=$(get_env "$BASH_SOURCE" "MCP_SERVICE_HTTP_SESSION_IDLE_TTL_SECONDS")
MCP_SERVICE_HTTP_MAX_SESSIONS=$(get_env "$BASH_SOURCE" "MCP_SERVICE_HTTP_MAX_SESSIONS")

DOCKER_HUB_URL=$(get_env "$BASH_SOURCE" "DOCKER_HUB_URL")
DOCKER_HUB_SERVICE_REPOSITORY=$(get_env "$BASH_SOURCE" "MCP_SERVICE_DOCKER_HUB_REPOSITORY_NAME")

if [ -z "$DOCKER_HUB_SERVICE_REPOSITORY" ]; then
    DOCKER_HUB_SERVICE_REPOSITORY=$(get_env "$BASH_SOURCE" "HOST_SERVICE_DOCKER_HUB_REPOSITORY_NAME")
fi

if [ -z "$DOCKER_HUB_SERVICE_REPOSITORY" ]; then
    DOCKER_HUB_SERVICE_REPOSITORY=$(get_env "$BASH_SOURCE" "API_SERVICE_DOCKER_HUB_REPOSITORY_NAME")
fi

GITHUB_TOKEN=$(get_env "$BASH_SOURCE" "GITHUB_TOKEN")
GITHUB_REPOSITORY=$(get_env "$BASH_SOURCE" "GITHUB_REPOSITORY")

PORTAINER_URL=$PORTAINER_SERVICE_SUBDOMAIN.$DOMAIN

if [ -z "$API_SERVICE_SUBDOMAIN" ]
then
    API_SERVICE_URL=$DOMAIN
else
    API_SERVICE_URL=$API_SERVICE_SUBDOMAIN.$DOMAIN
fi

if [ -z "$SERVICE_SUBDOMAIN" ]
then
    SERVICE_A="@"
    SERVICE_URL=$DOMAIN
else
    SERVICE_A=$SERVICE_SUBDOMAIN
    SERVICE_URL=$SERVICE_SUBDOMAIN.$DOMAIN
fi

if [ -z "$DOCKER_HUB_SERVICE_REPOSITORY" ]
then
    echo "No docker hub repository name for service $SERVICE_NAME"
    exit 0
fi

configure_mcp_clients() {
    ../mcp/setup-project-mcp.sh "$1" \
        --env-file "$PWD/.env" \
        --remote-url "https://$SERVICE_URL/mcp" \
        --environment "${ENVIRONMENT_TYPE:-production}" \
        --output-dir "${MCP_CLIENT_CONFIG_OUTPUT_DIR:-$PWD/../../.artifacts/mcp-client-configs}"
}

if [ "$1" != "down" ]
then
    configure_mcp_clients --check-clients || exit 1

    ./domain.sh present $SERVICE_URL $SERVICE_A && \
    ./pull_docker_image.sh "$DOCKER_HUB_URL/$DOCKER_HUB_SERVICE_REPOSITORY" "$ENVIRONMENT_TYPE" && \
    ansible_with_vars ./mcp/create_mcp.yaml \
        SERVICE_NAME PORTAINER_URL PORTAINER_USERNAME PORTAINER_PASSWORD DOCKER_HUB_URL \
        DOCKER_HUB_SERVICE_REPOSITORY API_SERVICE_URL RBAC_JWT_SECRET \
        REDIS_PASSWORD REDIS_PORT MCP_SERVICE_ALLOW_RBAC_SECRET_FALLBACK \
        MCP_SERVICE_ALLOWED_ORIGINS MCP_SERVICE_INTERNAL_TOKEN_EXCHANGE_SECRET \
        MCP_SERVICE_OAUTH_JWT_SECRET MCP_SERVICE_OAUTH_AUTH_CODE_TTL_SECONDS \
        MCP_SERVICE_OAUTH_CLIENT_TTL_SECONDS MCP_SERVICE_HTTP_MAX_BODY_BYTES MCP_SERVICE_HTTP_SESSION_IDLE_TTL_SECONDS MCP_SERVICE_HTTP_MAX_SESSIONS MCP_SERVICE_OAUTH_ACCESS_TOKEN_TTL_SECONDS \
        MCP_SERVICE_OAUTH_REFRESH_TOKEN_TTL_SECONDS SERVICE_URL ENVIRONMENT_TYPE && \
    ansible_with_vars ./mcp/fill_github.yaml \
        GITHUB_TOKEN GITHUB_REPOSITORY PORTAINER_URL SERVICE_URL ENVIRONMENT_TYPE && \
    configure_mcp_clients --write-clients
else
    ansible_with_vars ./mcp/clear_github.yaml \
        GITHUB_TOKEN GITHUB_REPOSITORY ENVIRONMENT_TYPE && \
    ansible_with_vars ./mcp/delete_mcp.yaml \
        SERVICE_NAME && \
    ./domain.sh down $SERVICE_URL $SERVICE_A
fi
