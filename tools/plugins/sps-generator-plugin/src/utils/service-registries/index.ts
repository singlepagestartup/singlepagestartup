import { names, type Tree } from "@nx/devkit";
import pluralize from "pluralize";
import ts from "typescript";

export const moduleDependencyContract =
  ".agents/contracts/engineering/module-dependencies.md";

const modulesDirectory = "libs/modules";
const appLib = "backend/app/api/src/lib";
const repositoryLib = "backend/repository/database/src/lib";
const generated = "// Generated by the SPS service registry generator.\n";

interface IEntity {
  module: string;
  kind: "models" | "relations";
  name: string;
  directory: string;
}

interface IRelationEndpoints {
  owner?: IEntity;
  child?: IEntity;
}

function readModuleOrder(tree: Tree) {
  const contract = tree.read(moduleDependencyContract, "utf8") ?? "";
  const order = Array.from(
    contract.matchAll(/^\d+\. `([^`]+)`\r?$/gm),
    ([, module]) => module,
  );
  if (!order.length || order.length !== new Set(order).size) {
    throw new Error(`Invalid module order in ${moduleDependencyContract}`);
  }
  return order;
}

export function assertServiceModule(tree: Tree, module: string) {
  if (!readModuleOrder(tree).includes(module)) {
    throw new Error(
      `Add the approved position of "${module}" to ${moduleDependencyContract} first`,
    );
  }
}

function listEntities(tree: Tree, module: string): IEntity[] {
  const entities: IEntity[] = [];
  const kinds = ["models", "relations"] as const;
  for (const kind of kinds) {
    const collection = `${modulesDirectory}/${module}/${kind}`;
    for (const name of tree.children(collection).sort()) {
      const directory = `${collection}/${name}`;
      if (tree.isFile(`${directory}/${appLib}/bootstrap.ts`)) {
        entities.push({ module, kind, name, directory });
      }
    }
  }
  return entities;
}

function entityId(entity: IEntity) {
  return `${entity.module}/${entity.kind}/${entity.name}`;
}

function entityRouteName(entity: IEntity) {
  if (entity.kind === "relations") {
    return entity.name;
  }
  return pluralize(entity.name);
}

function readRelationReferences(tree: Tree, relation: IEntity) {
  const lib = `${relation.directory}/${repositoryLib}`;
  const references: string[] = [];
  for (const file of ["schema.ts", "fields/singlepage.ts"]) {
    const source = tree.read(`${lib}/${file}`, "utf8") ?? "";
    const aliases = new Map(
      Array.from(
        source.matchAll(
          /\bTable\s+as\s+(\w+)\s*}\s*from\s+["']@sps\/([^/]+\/(?:models|relations)\/[^/]+)\/backend\/repository\/database["']/g,
        ),
        ([, alias, id]) => [alias, id],
      ),
    );
    for (const [, alias] of source.matchAll(
      /\.references\(\s*\(\)\s*=>\s*(\w+)\.id/g,
    )) {
      const id = aliases.get(alias);
      if (id) {
        references.push(id);
      }
    }
  }
  return references;
}

function relationEndpoints(
  tree: Tree,
  relation: IEntity,
  localEntities: IEntity[],
): IRelationEndpoints {
  const references = readRelationReferences(tree, relation);
  const candidates = localEntities.filter(
    (entity) => entity !== relation && references.includes(entityId(entity)),
  );
  // Some relations have additional foreign keys. Their left endpoint is the
  // longest matching prefix, such as StoresToProducts in StoresToProductsToAttributes.
  const prefixOwner = candidates
    .filter((entity) =>
      relation.name.startsWith(`${entityRouteName(entity)}-to-`),
    )
    .sort(
      (left, right) =>
        entityRouteName(right).length - entityRouteName(left).length,
    )[0];
  const owner =
    prefixOwner ??
    candidates.find(
      (entity) => references.length === 2 && entityId(entity) === references[0],
    );
  if (!owner) {
    return {};
  }
  const rightName = prefixOwner
    ? relation.name.slice(entityRouteName(owner).length + "-to-".length)
    : undefined;
  const child =
    candidates.find(
      (entity) => entity !== owner && entityRouteName(entity) === rightName,
    ) ??
    candidates.find(
      (entity) =>
        entity !== owner &&
        references.length === 2 &&
        entityId(entity) === references[1],
    );
  return { owner, child };
}

function selectLocalServices(tree: Tree, entities: IEntity[]) {
  const edges = new Map(entities.map((entity) => [entity, new Set<IEntity>()]));
  for (const relation of entities.filter(
    (entity) => entity.kind === "relations",
  )) {
    const { owner, child } = relationEndpoints(tree, relation, entities);
    if (owner) {
      edges.get(owner)?.add(relation);
    }
    if (owner && child) {
      edges.get(owner)?.add(child);
      edges.get(relation)?.add(child);
    }
  }
  const visiting = new Set<IEntity>();
  const visited = new Set<IEntity>();
  function visit(entity: IEntity) {
    if (visiting.has(entity)) {
      const cycle = [...visiting, entity].map(entityId).join(" → ");
      throw new Error(`Circular service ownership: ${cycle}`);
    }
    if (visited.has(entity)) {
      return;
    }
    visiting.add(entity);
    for (const dependency of edges.get(entity) ?? []) {
      visit(dependency);
    }
    visiting.delete(entity);
    visited.add(entity);
  }
  for (const entity of entities) {
    visit(entity);
  }
  return edges;
}

function writeChanged(tree: Tree, path: string, source: string) {
  if (tree.read(path, "utf8") !== source) {
    tree.write(path, source);
  }
}

function orderByName(left: IEntity, right: IEntity) {
  return left.name.localeCompare(right.name);
}

function entityAccess(entities: IEntity[]) {
  const imports: string[] = [];
  const properties: string[] = [];
  const used = new Set<string>();
  for (const entity of entities) {
    const { className, propertyName } = names(entity.name);
    if (used.has(propertyName)) {
      throw new Error(
        `Duplicate service registry key ${entity.module}.${propertyName}`,
      );
    }
    used.add(propertyName);
    const factory = `create${className}Service`;
    imports.push(
      `import { createService as ${factory} } from "@sps/${entityId(entity)}/${appLib}/bootstrap";`,
    );
    properties.push(
      `get ${propertyName}() {\n  return ${factory}(assembly);\n},`,
    );
  }
  return { imports, properties };
}

function renderProperties(properties: string[], depth: number) {
  const indentation = " ".repeat(depth);
  return properties
    .map((property) =>
      property
        .split("\n")
        .map((line) => indentation + line)
        .join("\n"),
    )
    .join("\n");
}

function renderAccess({
  imports,
  properties,
  factory,
}: {
  imports: string[];
  properties: string[];
  factory: "createServices" | "createModules" | "createModule";
}) {
  const hasProperties = properties.length > 0;
  const argument = hasProperties ? "assembly" : "_assembly";
  const result = hasProperties
    ? `{\n${renderProperties(properties, 4)}\n  }`
    : "{}";
  return [
    generated.trimEnd(),
    'import type { IAppAssembly } from "@sps/shared-backend-api";',
    ...imports,
    "",
    `export function ${factory}(${argument}: IAppAssembly) {`,
    `  return ${result};`,
    "}",
    "",
  ].join("\n");
}

function writeModuleViews(
  tree: Tree,
  module: string,
  entities: IEntity[],
  lowerModules: string[],
) {
  const directory = `${modulesDirectory}/${module}/${appLib}`;
  writeChanged(
    tree,
    `${directory}/services.ts`,
    renderAccess({
      ...entityAccess(entities),
      factory: "createServices",
    }),
  );

  const imports: string[] = [];
  const properties: string[] = [];
  for (const lowerModule of lowerModules) {
    const { className, propertyName } = names(lowerModule);
    const factory = `create${className}Services`;
    imports.push(
      `import { createServices as ${factory} } from "@sps/${lowerModule}/${appLib}/services";`,
    );
    properties.push(
      `get ${propertyName}() {\n  return assembly.getOrCreate(${factory});\n},`,
    );
  }
  writeChanged(
    tree,
    `${directory}/modules.ts`,
    renderAccess({ imports, properties, factory: "createModules" }),
  );
}

function writeEntityView(tree: Tree, entity: IEntity, dependencies: IEntity[]) {
  const lowerView = `@sps/${entity.module}/${appLib}/modules`;
  const directory = `${entity.directory}/${appLib}/service`;
  const localView = `${directory}/module.ts`;
  const legacyView = `${directory}/modules.ts`;
  const localSource = tree.read(localView, "utf8");
  const hasLocalServices = dependencies.length > 0;
  if (
    hasLocalServices &&
    localSource !== null &&
    !localSource.startsWith(generated)
  ) {
    throw new Error(
      `Cannot overwrite a manually maintained registry in ${localView}`,
    );
  }
  const path = `${directory}/singlepage/index.ts`;
  const source = tree.read(path, "utf8");
  if (!source) {
    throw new Error(`Cannot find the service implementation in ${path}`);
  }
  const updated = updateEntityService(
    path,
    source,
    lowerView,
    hasLocalServices,
  );
  if (hasLocalServices) {
    writeChanged(
      tree,
      localView,
      renderAccess({
        ...entityAccess(dependencies),
        factory: "createModule",
      }),
    );
  } else if (localSource?.startsWith(generated)) {
    tree.delete(localView);
  }
  if (tree.read(legacyView, "utf8")?.startsWith(generated)) {
    tree.delete(legacyView);
  }

  writeChanged(tree, path, updated);
}

interface ISourceEdit {
  start: number;
  end: number;
  text: string;
}

function registryGetter(name: "module" | "modules", factory: string) {
  return `  get ${name}() {\n    return this.appAssembly.getOrCreate(${factory});\n  }`;
}

function updateEntityService(
  path: string,
  source: string,
  lowerView: string,
  hasLocalServices: boolean,
) {
  const parsed = ts.createSourceFile(path, source, ts.ScriptTarget.Latest);
  const service = parsed.statements.find(
    (node): node is ts.ClassDeclaration =>
      ts.isClassDeclaration(node) && node.name?.text === "Service",
  );
  if (!service) {
    throw new Error(`Cannot find the Service class in ${path}`);
  }
  const edits: ISourceEdit[] = [];
  const newImports: string[] = [];
  const modulesImport = findFactoryImport(parsed, "createModules", [
    lowerView,
    "../modules",
  ]);
  if (!modulesImport) {
    newImports.push(`import { createModules } from "${lowerView}";`);
  } else if (modulesImport.moduleSpecifier.text !== lowerView) {
    assertDedicatedImport(parsed, modulesImport, "createModules");
    edits.push({
      start: modulesImport.moduleSpecifier.getStart(parsed),
      end: modulesImport.moduleSpecifier.end,
      text: `"${lowerView}"`,
    });
  }
  const localImport = findFactoryImport(parsed, "createModule", ["../module"]);
  const modulesGetter = service.members.find(
    (member) =>
      ts.isGetAccessor(member) && member.name.getText(parsed) === "modules",
  );
  const localGetter = service.members.find(
    (member) =>
      ts.isGetAccessor(member) && member.name.getText(parsed) === "module",
  );
  const newGetters: string[] = [];
  if (!modulesGetter) {
    newGetters.push(registryGetter("modules", "createModules"));
  }
  if (hasLocalServices) {
    if (!localImport) {
      newImports.push('import { createModule } from "../module";');
    }
    if (!localGetter) {
      newGetters.push(registryGetter("module", "createModule"));
    }
  } else if (localImport) {
    assertDedicatedImport(parsed, localImport, "createModule");
    const defaultGetter = registryGetter("module", "createModule").trimStart();
    if (localGetter?.getText(parsed) !== defaultGetter) {
      throw new Error(`Cannot remove a customized module getter in ${path}`);
    }
    const start = localGetter.getStart(parsed);
    const leading = source.slice(localGetter.getFullStart(), start);
    edits.push({
      start: localImport.getStart(parsed),
      end: localImport.end + Number(source[localImport.end] === "\n"),
      text: "",
    });
    edits.push({
      start: leading.trim() ? start : localGetter.getFullStart(),
      end: localGetter.end,
      text: "",
    });
  }
  if (newImports.length) {
    edits.push({ start: 0, end: 0, text: `${newImports.join("\n")}\n` });
  }
  if (newGetters.length) {
    const start = modulesGetter?.end ?? service.members.pos;
    const before = modulesGetter ? "\n\n" : "\n";
    const after = source[start] === "\n" ? "" : "\n";
    edits.push({
      start,
      end: start,
      text: `${before}${newGetters.join("\n\n")}${after}`,
    });
  }
  return edits
    .sort((left, right) => right.start - left.start)
    .reduce(
      (result, { start, end, text }) =>
        `${result.slice(0, start)}${text}${result.slice(end)}`,
      source,
    );
}

function findFactoryImport(
  source: ts.SourceFile,
  name: string,
  paths: string[],
) {
  return source.statements.find(
    (
      statement,
    ): statement is ts.ImportDeclaration & {
      moduleSpecifier: ts.StringLiteral;
    } => {
      if (
        !ts.isImportDeclaration(statement) ||
        !ts.isStringLiteral(statement.moduleSpecifier)
      ) {
        return false;
      }
      const clause = statement.importClause;
      const bindings = clause?.namedBindings;
      const named =
        bindings && ts.isNamedImports(bindings)
          ? bindings.elements.find((binding) => binding.name.text === name)
          : undefined;
      const namespace =
        bindings &&
        ts.isNamespaceImport(bindings) &&
        bindings.name.text === name;
      if (!named && !namespace && clause?.name?.text !== name) {
        return false;
      }
      if (
        !named ||
        (named.propertyName && named.propertyName.text !== name) ||
        named.isTypeOnly ||
        clause?.isTypeOnly ||
        !paths.includes(statement.moduleSpecifier.text)
      ) {
        throw new Error(`Conflicting ${name} import in ${source.fileName}`);
      }
      return true;
    },
  );
}

function assertDedicatedImport(
  source: ts.SourceFile,
  statement: ts.ImportDeclaration,
  name: string,
) {
  const clause = statement.importClause;
  const bindings = clause?.namedBindings;
  if (
    clause?.name ||
    !bindings ||
    !ts.isNamedImports(bindings) ||
    bindings.elements.length !== 1
  ) {
    throw new Error(
      `Use a dedicated ${name} import before regenerating ${source.fileName}`,
    );
  }
}

export function synchronizeServiceRegistries(tree: Tree) {
  const registered = readModuleOrder(tree);
  const modules = registered.filter((module) =>
    tree.isFile(`${modulesDirectory}/${module}/${appLib}/bootstrap.ts`),
  );
  for (const [index, module] of modules.entries()) {
    const entities = listEntities(tree, module).sort(orderByName);
    writeModuleViews(tree, module, entities, modules.slice(index + 1));
    for (const [entity, dependencies] of selectLocalServices(tree, entities)) {
      writeEntityView(tree, entity, [...dependencies].sort(orderByName));
    }
  }
}
