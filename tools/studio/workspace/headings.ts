const canonicalNames = new Map([
  ...Object.entries(aliases),
  ...Object.keys(RUSSIAN_HEADINGS).map(
    (en) => [en.toLowerCase(), en] as [string, string],
  ),
]);
export function canonicalHeading(value: string): string {
  return canonicalNames.get(value.trim().toLowerCase()) ?? value.trim();
}
export function localizedHeading(value: string): string {
  return RUSSIAN_HEADINGS[canonicalHeading(value)] ?? value;
}
export function canonicalMarkdownHeadings(source: string): string {
  return source.replace(
    /^(#{1,6}) (.+)$/gm,
    (_, marker: string, title: string) =>
      `${marker} ${canonicalHeading(title)}`,
  );
}
